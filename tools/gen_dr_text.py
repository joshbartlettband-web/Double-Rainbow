#!/usr/bin/env python3
"""Double Rainbow's codex text (firmware/src/dr_codex.inc) -> build/gen/dr_codex.h, packed with a Huffman code.
  python3 tools/gen_dr_text.py OUT.h
The codex is twenty lines a character, about 500 bytes of plain text each. One canonical Huffman code over the
letters (each line ends in a 0) packs it to a little over half. dr.c dr_tx unpacks one line when it is drawn:
  DR_TXT_HUFF  the number of codes of each length 1..15, then the letters in code order (as tools/art/gen_dr_art.py
               packs the sprites' runs; the same decoder, a bit at a time, no table in RAM)
  DR_TXT_AT    where each character's twenty lines start, in bits
  DR_TXT       the bits, MSB first"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "art"))
from gen_dr_art import huff_lengths, HC_MAXLEN   # noqa: E402

NLINE = 20


def lines():
    src = (ROOT / "firmware" / "src" / "dr_codex.inc").read_text()
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    strs = [s.encode("ascii") for s in re.findall(r'"((?:[^"\\]|\\.)*)"', src)]
    if len(strs) % NLINE:
        sys.exit(f"gen_dr_text: {len(strs)} lines in the codex, not twenty a character")
    return [strs[i:i + NLINE] for i in range(0, len(strs), NLINE)]


def main():
    out = Path(sys.argv[1])
    chars = lines()
    count = {}
    for ch in chars:
        for s in ch:
            for b in s + b"\0":
                count[b] = count.get(b, 0) + 1
    length = huff_lengths(count)
    order = sorted(count, key=lambda b: (length[b], b))
    code, c, prev = {}, 0, length[order[0]]
    for b in order:
        c <<= length[b] - prev
        prev = length[b]
        code[b] = c
        c += 1
    table = [sum(1 for b in order if length[b] == n) for n in range(1, HC_MAXLEN + 1)] + order
    bits, at = [], []
    for ch in chars:
        at.append(len(bits))
        for s in ch:
            for b in s + b"\0":
                bits += [(code[b] >> k) & 1 for k in range(length[b] - 1, -1, -1)]
    data = bytearray()
    for i in range(0, len(bits), 8):
        byte = bits[i:i + 8] + [0] * (8 - len(bits[i:i + 8]))
        data.append(sum(v << (7 - k) for k, v in enumerate(byte)))
    data += b"\0\0"
    # the self-check: the decoder as dr.c has it, every line back
    for k, ch in enumerate(chars):
        pos = at[k]
        for s in ch:
            got = bytearray()
            while True:
                cd = first = idx = 0
                for ln in range(HC_MAXLEN):
                    cd |= (data[pos >> 3] >> (7 - (pos & 7))) & 1
                    pos += 1
                    if cd - first < table[ln]:
                        break
                    idx += table[ln]
                    first = (first + table[ln]) << 1
                    cd <<= 1
                b = table[HC_MAXLEN + idx + cd - first]
                if not b:
                    break
                got.append(b)
            assert bytes(got) == s, (k, s, got)
    raw = sum(len(s) + 1 for ch in chars for s in ch)
    fmt = lambda xs: ",".join(str(x) for x in xs)
    out.write_text("\n".join([
        "/* generated by tools/gen_dr_text.py from firmware/src/dr_codex.inc: the codex, packed */",
        "#pragma once",
        "#include <stdint.h>",
        f"#define DR_TXT_NCHAR {len(chars)}u",
        f"static const uint8_t DR_TXT_HUFF[{len(table)}] = {{{fmt(table)}}};",
        f"static const uint32_t DR_TXT_AT[{len(at)}] = {{{fmt(at)}}};",
        f"static const uint8_t DR_TXT[{len(data)}] = {{{fmt(data)}}};",
        ""]))
    print(f"dr text: {len(chars)} characters, {raw} B of text in {len(data)} B -> {out}")


if __name__ == "__main__":
    main()
