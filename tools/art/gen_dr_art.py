#!/usr/bin/env python3
"""Double Rainbow's sprites (art/sprites/*.png, made by tools/art/procchar.py) -> a C header (run by tools/build.py
generate()).
  gen_dr_art.py OUT.h
Each sprite: its size, 15 colours (RGB565; index 0 is clear) and its pixels as runs, row-major, a byte a run:
index << 4 | (length - 1), 1..16 pixels. Fails if a sprite has more than 15 colours."""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SPRITES = ["vesper", "shard", "squall", "wick", "tock", "mote", "murk", "bog", "hush", "tumbler", "glint", "hermit"]          # the cast's order (firmware/src/dr.c DR_CAST)


def rgb565(c):
    r, g, b = c[:3]
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def pack(name):
    im = Image.open(ROOT / "art" / "sprites" / f"{name}.png").convert("RGBA")
    w, h = im.size
    px = list(im.getdata())
    pal = []
    idx = []
    for p in px:
        if p[3] < 128:
            idx.append(0)
            continue
        c = rgb565(p)
        if c not in pal:
            pal.append(c)
        idx.append(pal.index(c) + 1)
    if len(pal) > 15:
        raise SystemExit(f"{name}: {len(pal)} colours, at most 15 (tools/art/procchar.py)")
    runs, i = [], 0
    while i < len(idx):
        j = i
        while j < len(idx) and idx[j] == idx[i] and j - i < 16:
            j += 1
        runs.append(idx[i] << 4 | (j - i - 1))
        i = j
    return w, h, pal + [0] * (15 - len(pal)), runs


def main():
    out = ["/* generated by tools/art/gen_dr_art.py from art/sprites/: Double Rainbow's characters */", "#pragma once",
           "#include <stdint.h>", "typedef struct { uint8_t w, h; uint16_t pal[15]; uint16_t n; const uint8_t *run; } dr_sprite_t;"]
    total = 0
    for name in SPRITES:
        w, h, pal, runs = pack(name)
        total += len(runs) + 30 + 6
        out.append(f"static const uint8_t DR_RUN_{name.upper()}[{len(runs)}] = {{")
        for i in range(0, len(runs), 24):
            out.append("    " + ", ".join(str(b) for b in runs[i:i + 24]) + ",")
        out.append("};")
    out.append(f"static const dr_sprite_t DR_SPRITES[{len(SPRITES)}] = {{")
    for name in SPRITES:
        w, h, pal, runs = pack(name)
        out.append(f"    {{{w}, {h}, {{" + ", ".join(f"0x{c:04x}" for c in pal) + f"}}, {len(runs)}, DR_RUN_{name.upper()}}},")
    out += ["};", f"/* {total} B in all */", ""]
    Path(sys.argv[1]).write_text("\n".join(out))
    print(f"dr art: {len(SPRITES)} sprites, {total} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
