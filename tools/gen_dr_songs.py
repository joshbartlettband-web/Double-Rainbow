PC = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def note(tok):
    m = re.fullmatch(r"([A-G])([#b]?)(\d)/(\d+)|r/(\d+)", tok)
    if not m:
        raise SystemExit(f"songs: {tok!r} is not NAME OCTAVE / LENGTH")
    if m[5]:
        return 0, int(m[5])
    n = 12 * (int(m[3]) + 1) + PC[m[1]] + {"#": 1, "b": -1, "": 0}[m[2]]
    return n, int(m[4])


def main():
    out = ["/* generated by tools/gen_dr_songs.py: Double Rainbow's TRACE songs */", "#pragma once", "#include <stdint.h>",
           "typedef struct { const char *title, *who; uint8_t bpm, n, flats; const uint8_t *nd; } dr_song_t;"]
    total = 0
    for i, (title, who, bpm, text) in enumerate(SONGS):
        notes = [note(t) for t in text.split()]
        played = [n for n, _ in notes if n]
        if min(played) < LO or max(played) > HI:
            raise SystemExit(f"songs: {title} reaches {min(played)} .. {max(played)}, off the keys ({LO} .. {HI})")
        if any(d < 1 or d > 16 for _, d in notes) or len(notes) > 255:
            raise SystemExit(f"songs: {title}: a length out of 1 .. 16, or too many notes")
        out.append(f"static const uint8_t DR_SONG_{i}[{2 * len(notes)}] = {{" +
                   ", ".join(f"{n}, {d}" for n, d in notes) + "};")
        total += 2 * len(notes) + len(title) + len(who) + 12
    out.append(f"static const dr_song_t DR_SONGS[{len(SONGS)}] = {{")
    for i, (title, who, bpm, text) in enumerate(SONGS):
        flats = int(len(re.findall(r"[A-G]b", text)) > text.count("#"))   # the screen spells the notes the song's way
        out.append(f'    {{"{title}", "{who}", {bpm}, {len(text.split())}, {flats}, DR_SONG_{i}}},')
    out += ["};", f"#define DR_NSONGS {len(SONGS)}u", f"/* {total} B in all */", ""]
    Path(sys.argv[1]).write_text("\n".join(out))
    print(f"dr songs: {len(SONGS)} songs, {total} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
